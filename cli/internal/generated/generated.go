var dirMarkers = []string{"/__generated__/"}

var contentMarkers = []string{
	"do not edit",
	"do not modify",
	"generated by",
	"autogenerated",
	"auto-generated",
	"@generated",
	"<auto-generated>",
}

func IsGeneratedFilename(path string) bool {
	base := strings.ToLower(filepath.Base(path))
	for _, pattern := range filenamePatterns {
		if matched, _ := filepath.Match(pattern, base); matched {
			return true
		}
	}
	if strings.Contains(base, ".generated.") || strings.Contains(base, "_generated.") {
		return true
	}
	slash := strings.ToLower(filepath.ToSlash(path))
	for _, marker := range dirMarkers {
		if strings.Contains(slash, marker) {
			return true
		}
	}
	return false
}

func HasGeneratedMarker(src []byte) bool {
	head := src
	if len(head) > 512 {
		head = head[:512]
	}
	lower := bytes.ToLower(head)
	for _, marker := range contentMarkers {
		if bytes.Contains(lower, []byte(marker)) {
			return true
		}
	}
	return false
}

func IsGenerated(path string, src []byte) bool {
	return IsGeneratedFilename(path) || HasGeneratedMarker(src)
}
