func TestHasGeneratedMarker(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{"protoc-gen-go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage main\n", true},
		{"protoc compiler", "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n", true},
		{"protoc java", "// Generated by the protocol buffer compiler (version 4.28.0)\n", true},
		{"kotlin grpc", "/*\n * Generated by the gRPC Kotlin plugin.\n */\n", true},
		{"flatc", "// automatically generated by the FlatBuffers compiler\n", true},
		{"prost", "// @generated\n", true},
		{"autogenerated hash", "// Autogenerated. Go away.\n", true},
		{"auto-generated", "# auto-generated file\n", true},
		{"source generated cs", "// <auto-generated>\n", true},
		{"csharp sdk marker", "// ------------------------------------------------------------------------------\n// <auto-generated>\n", true},
		{"plain source", "package main\n\nfunc main() {}\n", false},
		{"generated beyond 512 bytes", string(make([]byte, 600)) + "generated by", false},
		{"dart generated header", "// GENERATED CODE - DO NOT MODIFY BY HAND\n", true},
		{"graphql codegen", "/* eslint-disable */\n// @generated\n// This file is generated by GraphQL codegen\n", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := HasGeneratedMarker([]byte(tt.src)); got != tt.want {
				t.Errorf("HasGeneratedMarker(%q) = %v, want %v", tt.src, got, tt.want)
			}
		})
	}
}

func TestIsGenerated(t *testing.T) {
	if !IsGenerated(filepath.Join("a", "user.g.dart"), []byte("class A {}")) {
		t.Error("generated filename should be detected")
	}
	if !IsGenerated("plain.go", []byte("// Code generated by x. DO NOT EDIT.\n")) {
		t.Error("content marker should be detected")
	}
	if IsGenerated("plain.go", []byte("package main\n")) {
		t.Error("plain file should not be detected as generated")
	}
}
